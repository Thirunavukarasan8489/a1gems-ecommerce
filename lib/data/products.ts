export function getProduct(slug: string) {
  return products.find((p) => p.slug === slug && p.published);
}

export function getProductsByCategory(categorySlug: string) {
  return products.filter((p) => p.categorySlug === categorySlug && p.published);
}

export function getFeaturedProducts() {
  return products.filter((p) => p.featured && p.published);
}

export function getBestsellers() {
  return products.filter((p) => p.bestseller && p.published);
}

export function getRelatedProducts(product: Product, limit = 6) {
  return products
    .filter(
      (p) =>
        p.published &&
        p.id !== product.id &&
        p.categorySlug === product.categorySlug,
    )
    .concat(
      products.filter(
        (p) =>
          p.published &&
          p.id !== product.id &&
          p.categorySlug !== product.categorySlug &&
          p.featured,
      ),
    )
    .slice(0, limit);
}
